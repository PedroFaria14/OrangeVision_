from datetime import datetime
from typing import Protocol
from uuid import UUID


class AuthStore(Protocol):
    def consume_attempts(self, bucket_hashes: tuple[str, str], maximum: int) -> bool: ...
    def create_user(self, user_id: UUID, name: str, email: str, password_hash: str) -> None: ...
    def find_user(self, email: str) -> dict | None: ...
    def find_session(self, token_hash: str) -> dict | None: ...
    def replace_session(
        self, old_hash: str | None, token_hash: str, user_id: UUID, csrf: str, expires_at: datetime
    ) -> None: ...
    def revoke_session(self, token_hash: str) -> None: ...


class PasswordCodec(Protocol):
    def hash_password(self, password: str) -> str: ...
    def verify_password(self, stored_hash: str | None, password: str) -> bool: ...


class AnalysisReader(Protocol):
    def list_analyses(
        self, user_id: UUID, filters, limit: int, offset: int
    ) -> tuple[list[dict], int]: ...
    def find_analysis(self, user_id: UUID, analysis_id: UUID) -> dict | None: ...
    def summarize(self, user_id: UUID, filters) -> dict: ...
    def aggregate_daily(self, user_id: UUID, filters) -> list[dict]: ...
    def compare_periods(self, user_id: UUID, filters, current, previous) -> dict[str, dict]: ...
